package provision

import (
	"fmt"
	"strings"
	"unicode"

	"copper_control_plane/internal/storage"
)

const (
	maxGrubCmdlineExtra = 2048
	grubDropInRelPath   = "etc/default/grub.d/99-copper-cmdline.cfg"
)

func normalizeGrubCmdlineExtra(s string) string {
	return strings.Join(strings.Fields(strings.TrimSpace(s)), " ")
}

func validateGrubCmdlineExtra(s string) error {
	s = normalizeGrubCmdlineExtra(s)
	if s == "" {
		return nil
	}
	if len(s) > maxGrubCmdlineExtra {
		return fmt.Errorf("grub_cmdline_extra too long (max %d chars)", maxGrubCmdlineExtra)
	}
	for _, r := range s {
		if r < 32 || r == 127 || !unicode.IsPrint(r) {
			return fmt.Errorf("grub_cmdline_extra must be printable (no control characters)")
		}
	}
	// Keep the drop-in / sed path free of shell and quote breakage.
	if strings.ContainsAny(s, "\"'`$\\\n\r;") {
		return fmt.Errorf("grub_cmdline_extra must not contain quotes or shell metacharacters")
	}
	return nil
}

// GrubDropInContent returns /etc/default/grub.d/99-copper-cmdline.cfg (append-only).
func GrubDropInContent(extra string) string {
	extra = normalizeGrubCmdlineExtra(extra)
	if extra == "" {
		return ""
	}
	return "# Generated by Copper — append-only kernel cmdline extras\n" +
		"GRUB_CMDLINE_LINUX_DEFAULT=\"$GRUB_CMDLINE_LINUX_DEFAULT " + extra + "\"\n"
}

// FormatGrubCmdlineFinal joins image defaults + admin extras for preview/logging.
func FormatGrubCmdlineFinal(existing, extra string) string {
	existing = strings.Join(strings.Fields(strings.TrimSpace(existing)), " ")
	extra = normalizeGrubCmdlineExtra(extra)
	switch {
	case existing == "" && extra == "":
		return ""
	case existing == "":
		return extra
	case extra == "":
		return existing
	default:
		return existing + " " + extra
	}
}

// buildGrubCmdlineScript mounts the written root, appends extras to
// GRUB_CMDLINE_LINUX_DEFAULT via a grub.d drop-in, runs update-grub when
// possible, and falls back to patching grub.cfg linux lines for first boot.
func buildGrubCmdlineScript(disk, extra string) string {
	extra = normalizeGrubCmdlineExtra(extra)
	dropIn := GrubDropInContent(extra)
	return remotePrelude() + fmt.Sprintf(`
set -u
DEV=%s
EXTRA=%s
DROPIN_B64=%s
DROPIN_REL=%s
log() { printf '%%s\n' "$1"; }

log "GRUB_BEGIN dev=$DEV"
log "GRUB_CMDLINE_APPEND=$EXTRA"

if [ -z "$EXTRA" ]; then
  log "GRUB_SKIP empty extras"
  log "GRUB_CMDLINE_OK"
  exit 0
fi

partprobe "$DEV" 2>/dev/null || true
sleep 1

MNT=$(mktemp -d)
cleanup() {
  umount -R "$MNT" 2>/dev/null || true
  rm -rf "$MNT"
}
trap cleanup EXIT

ROOT=""
ESP=""
BOOT=""
while read -r name typ fstype parttype; do
  [ "$typ" = "part" ] || continue
  path="/dev/$name"
  case "$path" in
    "$DEV"*) ;;
    *) continue ;;
  esac
  pt=$(printf '%%s' "$parttype" | tr 'A-Z' 'a-z')
  lab=$(lsblk -ln -o LABEL "$path" 2>/dev/null | head -n1 | tr -d '\r')
  lab_lc=$(printf '%%s' "$lab" | tr 'A-Z' 'a-z')
  if [ "$pt" = "c12a7328-f81f-11d2-ba4b-00a0c93ec93b" ]; then
    ESP="$path"
    continue
  fi
  if [ "$pt" = "bc13c2ff-59e6-4262-a352-b275fd6f7172" ] || [ "$lab_lc" = "boot" ]; then
    BOOT="$path"
    continue
  fi
  if [ "$lab_lc" = "cloudimg-rootfs" ] || [ "$pt" = "0fc63daf-8483-4772-8e79-3d69d8477de4" ]; then
    case "$fstype" in ext2|ext3|ext4)
      ROOT="$path"
      ;;
    esac
  fi
done < <(lsblk -ln -o NAME,TYPE,FSTYPE,PARTTYPE "$DEV" 2>/dev/null)

if [ -z "$ROOT" ]; then
  while read -r name typ fstype; do
    [ "$typ" = "part" ] || continue
    case "$fstype" in ext2|ext3|ext4) ;; *) continue ;; esac
    path="/dev/$name"
    case "$path" in
      "$DEV"*) ;;
      *) continue ;;
    esac
    [ "$path" = "$BOOT" ] && continue
    if mount -o ro "$path" "$MNT" 2>/dev/null; then
      if [ -d "$MNT/etc" ]; then
        ROOT="$path"
        umount "$MNT" 2>/dev/null || true
        break
      fi
      umount "$MNT" 2>/dev/null || true
    fi
  done < <(lsblk -ln -o NAME,TYPE,FSTYPE "$DEV" 2>/dev/null)
fi

if [ -z "$ESP" ]; then
  while read -r name typ fstype; do
    [ "$typ" = "part" ] || continue
    [ "$fstype" = "vfat" ] || [ "$fstype" = "fat32" ] || continue
    path="/dev/$name"
    case "$path" in
      "$DEV"*) ;;
      *) continue ;;
    esac
    if mount -o ro "$path" "$MNT" 2>/dev/null; then
      if [ -d "$MNT/EFI" ] || [ -d "$MNT/efi" ]; then
        ESP="$path"
        umount "$MNT" 2>/dev/null || true
        break
      fi
      umount "$MNT" 2>/dev/null || true
    fi
  done < <(lsblk -ln -o NAME,TYPE,FSTYPE "$DEV" 2>/dev/null)
fi

if [ -z "$ROOT" ]; then
  log "ERROR: could not find root filesystem on $DEV"
  exit 40
fi
log "ROOT=$ROOT BOOT=${BOOT:-none} ESP=${ESP:-none}"

mount "$ROOT" "$MNT"
if [ -n "$BOOT" ]; then
  mkdir -p "$MNT/boot"
  mount "$BOOT" "$MNT/boot"
fi
if [ -n "$ESP" ]; then
  mkdir -p "$MNT/boot/efi"
  mount "$ESP" "$MNT/boot/efi"
fi

# Resolve image defaults the same way update-grub would (before our drop-in).
GRUB_CMDLINE_LINUX_DEFAULT=""
GRUB_CMDLINE_LINUX=""
set +e
[ -f "$MNT/etc/default/grub" ] && . "$MNT/etc/default/grub"
if [ -d "$MNT/etc/default/grub.d" ]; then
  for g in "$MNT/etc/default/grub.d"/*.cfg; do
    [ -f "$g" ] || continue
    case "$g" in
      */99-copper-cmdline.cfg) continue ;;
    esac
    . "$g"
  done
fi
set -e
EXISTING=$(printf '%%s' "${GRUB_CMDLINE_LINUX_DEFAULT:-}" | tr -s '[:space:]' ' ' | sed 's/^ //;s/ $//')
log "GRUB_CMDLINE_EXISTING=$EXISTING"
FINAL=$(printf '%%s %%s' "$EXISTING" "$EXTRA" | tr -s '[:space:]' ' ' | sed 's/^ //;s/ $//')
log "GRUB_CMDLINE_FINAL=$FINAL"

mkdir -p "$MNT/etc/default/grub.d"
printf '%%s' "$DROPIN_B64" | base64 -d > "$MNT/$DROPIN_REL"
if [ ! -s "$MNT/$DROPIN_REL" ]; then
  log "ERROR: failed to write GRUB drop-in"
  exit 41
fi
log "GRUB_DROPIN /$DROPIN_REL written"
log "--- drop-in ---"
cat "$MNT/$DROPIN_REL"

append_linux_lines() {
  _f="$1"
  [ -f "$_f" ] || return 0
  if grep -F -- "$EXTRA" "$_f" >/dev/null 2>&1; then
    log "GRUB_CFG_ALREADY $_f"
    return 0
  fi
  # Append EXTRA to linux / linuxefi menu lines only.
  awk -v extra="$EXTRA" '
    BEGIN { changed=0 }
    /^[[:space:]]*linux(efi)?[[:space:]]/ {
      print $0 " " extra
      changed=1
      next
    }
    { print }
    END { if (changed) exit 0; else exit 1 }
  ' "$_f" > "$_f.copper-new"
  st=$?
  if [ "$st" = "0" ]; then
    mv "$_f.copper-new" "$_f"
    log "GRUB_CFG_PATCHED $_f"
  else
    rm -f "$_f.copper-new"
    log "GRUB_CFG_NOP $_f"
  fi
}

updated=0
set +e
mount --bind /dev "$MNT/dev" 2>/dev/null
mount --bind /proc "$MNT/proc" 2>/dev/null
mount --bind /sys "$MNT/sys" 2>/dev/null
mount --bind /run "$MNT/run" 2>/dev/null
if [ -x "$MNT/usr/sbin/update-grub" ]; then
  chroot "$MNT" /usr/sbin/update-grub
  st=$?
elif [ -x "$MNT/usr/sbin/grub-mkconfig" ]; then
  chroot "$MNT" /usr/sbin/grub-mkconfig -o /boot/grub/grub.cfg
  st=$?
else
  st=127
fi
set -e
if [ "${st:-1}" = "0" ]; then
  updated=1
  log "GRUB_UPDATE_OK"
else
  log "GRUB_UPDATE_FAIL st=${st:-?} — falling back to grub.cfg patch"
fi

# Ensure first boot sees extras even if update-grub failed or was skipped.
append_linux_lines "$MNT/boot/grub/grub.cfg"
append_linux_lines "$MNT/boot/efi/EFI/ubuntu/grub.cfg"

if [ "$updated" != "1" ]; then
  if ! grep -R -F -- "$EXTRA" "$MNT/boot/grub/grub.cfg" "$MNT/boot/efi/EFI/ubuntu/grub.cfg" >/dev/null 2>&1; then
    log "ERROR: could not apply GRUB cmdline extras (update-grub failed and grub.cfg patch missed)"
    exit 42
  fi
fi

sync
log "GRUB_CMDLINE_OK final=$FINAL"
exit 0
`, storage.ShellQuote(disk),
		storage.ShellQuote(extra),
		storage.ShellQuote(b64(dropIn)),
		storage.ShellQuote(grubDropInRelPath))
}
